'use strict';
import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const context=vm.createContext({Map,Date});vm.runInContext(fs.readFileSync('public/experience.js','utf8')+'\nthis.todos=boardTodos;',context);
const base={id:'one',title:'活动',lifecycle:'scheduled',my_attendees:[],participants:[],finance:{}};
assert.equal(context.todos([base]).length,0);
assert.equal(context.todos([{...base,my_attendees:[{can_respond:true,confirmation_state:'pending'}]}])[0].kind,'conditions');
assert.equal(context.todos([{...base,my_attendees:[{can_respond:false,confirmation_state:'pending'}]}]).length,0);
assert.equal(context.todos([{...base,can_manage_roster:true,participants:[{withdrawal_requested:true}]}])[0].label,'处理退出申请');
assert.equal(context.todos([{...base,can_manage_roster:false,participants:[{withdrawal_requested:true}]}]).length,0);
assert.equal(context.todos([{...base,is_owner:true,minimum_participants:4,minimum_met:true}])[0].label,'决定是否成团');
assert.equal(context.todos([{...base,can_finish:true,estimated_over:true}])[0].label,'确认活动结束／延长');
assert.equal(context.todos([{...base,lifecycle:'ended',can_settle:true}])[0].kind,'settle');
assert.equal(context.todos([{...base,finance:{my_outstanding_cents:123}}])[0].kind,'finance');
assert.equal(context.todos([{...base,finance:{my_refund_due_cents:123}}])[0].label,'我的退款／垫付待收回');
assert.equal(context.todos([{...base,finance:{can_manage:true,detailed:true,state:'closed'}}]).length,0);
assert.equal(context.todos([{...base,finance:{can_manage:true,detailed:true,state:'collecting',pending_count:2}}]).length,2);
assert.equal(context.todos([{...base,claim_invitations:[{can_decide:true}]}])[0].label,'核对报名认领');
assert.equal(context.todos([{...base,claim_invitations:[{can_decide:false}]}]).length,0);
console.log('14 role and todo assertions passed');
