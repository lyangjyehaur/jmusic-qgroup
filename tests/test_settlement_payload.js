'use strict';
import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const context=vm.createContext({});
vm.runInContext(fs.readFileSync('public/settlements.js','utf8'),context);
const build=(...args)=>JSON.parse(JSON.stringify(context.settlementItemsPayload(...args)));
const people=[{id:'a'},{id:'b'}];
const selected={id:'item',scope:'selected',mode:'duration',allocations:[{person_id:'b'}],receipt:{version:1,item_id:'item'},receipt_digest:'old'};
assert.deepEqual(build([selected],people,3)[0].allocations,[{person_id:'b',minutes:180}]);
assert.deepEqual(build([{...selected,mode:'weights'}],people,3)[0].allocations,[{person_id:'b',weight:'1'}]);
assert.deepEqual(build([{...selected,mode:'fixed'}],people,3)[0].allocations,[{person_id:'b',amount:'0.00'}]);
assert.deepEqual(build([{...selected,mode:'equal'}],people,3)[0].allocations,[{person_id:'b'}]);
assert.deepEqual(build([{...selected,scope:'common'}],people,2)[0].allocations,[{person_id:'a',minutes:120},{person_id:'b',minutes:120}]);
assert.deepEqual(build([{...selected,allocations:[{person_id:'b',minutes:0}]}],people,3)[0].allocations,[{person_id:'b',minutes:0}]);
assert.deepEqual(build([{...selected,mode:'weights',allocations:[{person_id:'b',weight:'0.5'},{person_id:'excluded',weight:'2'}]}],people,3)[0].allocations,[{person_id:'b',weight:'0.5'}]);
assert.deepEqual(build([{...selected,scope:'common',mode:'shares'}],people,3)[0].allocations,[]);
assert.deepEqual(build([selected],people,3)[0].receipt,selected.receipt);
assert.equal('receipt_digest' in build([selected],people,3)[0],false);
assert.deepEqual(selected.allocations,[{person_id:'b'}]);
console.log('11 settlement payload assertions passed');
