import assert from 'node:assert/strict';
import {createSelectionStore} from '../ui/music/selection-store.ts';

const store=createSelectionStore();
store.configure({entries:[{id:'a',text:'A',count:1},{id:'b',text:'B',count:4}]});
store.reset(['a',{id:'b',level:4}]);
assert.deepEqual(store.getSnapshot().order,['b','a']);
assert.equal(store.level('a'),3,'Legacy string selections still default to 常听');
const before=store.getSnapshot();
store.select('a',4);
assert.equal(before.levels.a,3,'Published snapshots must not be changed in place');
assert.deepEqual(store.getSnapshot().order,['b','a'],'Changing a level must not reorder focused rows');
const revision=store.startSaving();
store.remove('b');
assert.equal(store.acknowledgeSave(revision),false);
store.finishSaving();
assert.equal(store.getSnapshot().dirty,true,'A late save must preserve newer edits');
assert.deepEqual([...store.getSnapshot().ids],['a']);
store.startSaving();
store.finishSaving();
assert.equal(store.getSnapshot().dirty,true,'A failed save must preserve the draft');
assert.equal(store.acknowledgeSave(store.startSaving()),true);
store.finishSaving();
assert.equal(store.getSnapshot().dirty,false);
store.select('b',1);
assert.deepEqual(store.getSnapshot().order,['a','b']);
store.reset([]);
assert.equal(store.getSnapshot().ids.size,0);
assert.deepEqual(store.getSnapshot().levels,{});
assert.equal(store.getSnapshot().dirty,false);
console.log('Music selection data, stable order and in-flight save regression checks passed');
