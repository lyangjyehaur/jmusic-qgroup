'use strict';
import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync('public/app.js','utf8');
const dates=source.slice(source.indexOf('const deviceZone='),source.indexOf('function formStart()'));
const context=vm.createContext({Intl,Date,Error,BoardI18n:{locale:'zh-CN'}});
vm.runInContext(dates+';this.dates={wallDate,wallToISO,timeRange,endLabel};',context);
const {wallDate,wallToISO,timeRange,endLabel}=context.dates;
assert.equal(wallDate('2026-12-31T16:15:00Z','Asia/Shanghai'),'2027-01-01T00:15');
assert.equal(wallToISO('2027-01-01T00:15','Asia/Shanghai'),'2026-12-31T16:15:00.000Z');
assert.equal(wallToISO('2027-01-01T00:15','Asia/Tokyo'),'2026-12-31T15:15:00.000Z');
assert.equal(wallToISO('2027-01-01T00:15','UTC'),'2027-01-01T00:15:00.000Z');
assert.throws(()=>wallToISO('2026-03-08T02:30','America/New_York'),/没有这个本地时间/);
assert.throws(()=>wallToISO('2026-11-01T01:30','America/New_York'),/重复时段/);
assert.equal(wallToISO('2026-11-01T03:30','America/New_York'),'2026-11-01T08:30:00.000Z');
assert.throws(()=>wallToISO('2026-02-30T12:00','UTC'));
assert.match(endLabel('2026-12-31T15:00Z','2026-12-31T17:00Z','Asia/Shanghai'),/1月1日/);
assert.match(timeRange({starts_at:'2026-12-31T15:00Z',ends_at:'2026-12-31T17:00Z',timezone:'Asia/Shanghai'}),/GMT\+8/);
console.log('10 timezone and cross-day assertions passed');
