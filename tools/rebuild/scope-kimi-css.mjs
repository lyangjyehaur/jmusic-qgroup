// Preserve the prototype stylesheet as the source; only scope it away from retained
// business forms. Responsive rules, dimensions and component states stay verbatim.
import fs from 'node:fs';
import postcss from 'postcss';
const source = fs.readFileSync('apps/web/src/kimi/prototype.css', 'utf8');
const root = postcss.parse(source);
const shell = /\.(?:app-shell|sidebar|brand(?:-mark)?|side-nav|nav-item|sidebar-bottom|sidebar-account|main-column|topbar(?:-actions)?|global-search|top-account|account-wrap|popover|account-menu|account-summary|mobile-brand|mobile-dock|mobile-search-button|main-content|dock-item|inbox-button|unread-count)(?![\w-])/;
function scoped(selector, target) {
  const prefix=':where('+target+')';
  return [prefix+' '+selector,...(/^[.#[\:]/.test(selector)?[prefix+selector]:[])];
}
root.walkRules(rule => {
  if (rule.parent.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return;
  rule.selectors = rule.selectors.flatMap(selector => {
    if (selector === ':root') return '.kimi, .kimi-shell';
    if (selector.includes('[data-yahha-theme]')) return selector.replace('[data-yahha-theme]', '[data-yahha-theme].kimi-theme');
    if (selector.startsWith('html[data-density=')) { const match=selector.match(/^(html\[data-density=[^\]]+\])\s+(.+)$/); return scoped(match[2],'.kimi, .kimi-shell').map(value=>match[1]+' '+value); }
    if (/^(html|body)(?:\s|$)/.test(selector)) return selector.replace(/^(html|body)/, ':where(.kimi-shell)');
    return scoped(selector,shell.test(selector)?'.kimi-shell':'.kimi');
  });
});
fs.writeFileSync('apps/web/src/kimi/scoped.css', '/* Generated by tools/rebuild/scope-kimi-css.mjs from prototype.css. */\n' + root.toString());
