// Reuse the installed Yahha Button's actual stylesheet for semantic router links.
// No private class name is hardcoded: resolve it from the public component render.
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { Button } from 'yahha-ui';
import postcss from 'postcss';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const markup=renderToStaticMarkup(createElement(Button,null,'link'));
const base=markup.match(/class="([^" ]+)/)?.[1];if(!base)throw Error('Yahha Button class missing');
const css=postcss.parse(readFileSync(fileURLToPath(import.meta.resolve('yahha-ui/style.css')),'utf8'));
function pick(container){const out=postcss.root();for(const node of container.nodes??[]){if(node.type==='rule'){const selectors=node.selectors.filter(selector=>selector.includes('.'+base));if(selectors.length)out.append(node.clone({selectors:selectors.map(selector=>selector.replaceAll('.'+base,'.kimi-link-button'))}));}else if(node.type==='atrule'&&node.nodes){const inside=pick(node);if(inside.nodes.length){const copy=node.clone({nodes:[]});copy.append(inside.nodes);out.append(copy);}}}return out;}
writeFileSync('apps/web/src/kimi/button-links.css','/* Generated by tools/rebuild/build-kimi-button-links.mjs from yahha-ui Button. */\n'+pick(css).toString());
