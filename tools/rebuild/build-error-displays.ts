import ts from 'typescript';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { compileDisplayPair } from '../../apps/web/ui-language';
function choices(node:ts.Expression):string[]|undefined {
  if(ts.isStringLiteral(node))return[node.text];
  if(ts.isParenthesizedExpression(node))return choices(node.expression);
  if(ts.isConditionalExpression(node)){const left=choices(node.whenTrue),right=choices(node.whenFalse);if(left&&right)return[...left,...right];}
}
/** Explicit constructors only: no message lookup infers provenance at a catch site. */
export function collectErrorDisplays(source:string,filename:string,marker:'withApiError'|'withDomainError') {
  const tree=ts.createSourceFile(filename,source,ts.ScriptTarget.Latest,true),rows:Record<string,readonly [string,string]>={};let count=0;
  function visit(node:ts.Node) {
    if(ts.isCallExpression(node)&&ts.isIdentifier(node.expression)&&node.expression.text===marker){
      const error=node.arguments[0];
      if(node.arguments.length!==1||!error||!ts.isNewExpression(error)||!ts.isIdentifier(error.expression)||error.expression.text!=='DomainError')throw Error(`${filename}: ${marker} requires the original DomainError constructor`);
      const code=error.arguments?.[0],message=error.arguments?.[1],values=message&&choices(message);
      if(!code||!ts.isStringLiteral(code)||!values)throw Error(`${filename}: system error code and message branches must be fixed literals`);
      count++;for(const value of values)rows[JSON.stringify([code.text,value])]=compileDisplayPair(value);
    }
    ts.forEachChild(node,visit);
  }visit(tree);return{rows,count};
}
export function buildErrorDisplays(check=false) {
  const result=[];
  for(const [root,marker,name] of [['apps/api/src','withApiError','apiErrorPairs'],['packages/domain/src','withDomainError','domainErrorPairs']] as const){
    const rows:Record<string,readonly [string,string]>={};let count=0;
    for(const file of readdirSync(root).filter(name=>name.endsWith('.ts')&&!name.endsWith('.test.ts')&&!name.endsWith('.generated.ts')).sort()){
      const found=collectErrorDisplays(readFileSync(root+'/'+file,'utf8'),root+'/'+file,marker);Object.assign(rows,found.rows);count+=found.count;
    }
    const ordered=Object.fromEntries(Object.entries(rows).sort(([a],[b])=>a<b?-1:a>b?1:0));
    const output='// Generated by tools/rebuild/build-error-displays.ts; fixed system displays only.\nexport const '+name+':Readonly<Record<string,readonly [string,string]>> = '+JSON.stringify(ordered,null,2)+';\n',path=root+'/error-pairs.generated.ts';
    if(check){if(readFileSync(path,'utf8')!==output)throw Error('Stale error display pairs: '+path);}else writeFileSync(path,output);
    result.push({root,constructors:count,pairs:Object.keys(ordered).length});
  }return result;
}
if(process.argv[1]&&import.meta.url===pathToFileURL(resolve(process.argv[1])).href){
  const args=process.argv.slice(2);if(args.length>1||args.length===1&&args[0]!=='--check')throw Error('Use --check or no arguments');
  process.stdout.write(JSON.stringify(buildErrorDisplays(args[0]==='--check'))+'\n');
}
