"""Regenerate ONLY schema from frozen committed Python, never from a live DB.

No Python is used by the replacement runtime. This is a build-time audit tool.
"""
import json
from pathlib import Path
import sqlite3
import subprocess
import sys
import tarfile
import tempfile

ROOT = Path(__file__).resolve().parents[2]
BASE = '8da877857f163853c449474e168534e2e493121b'
with tempfile.TemporaryDirectory(prefix='qgroup-schema-') as folder:
    root = Path(folder)
    archive = root / 'baseline.tar'
    subprocess.run(['git', 'archive', '-o', str(archive), BASE, 'qgroup_core'], cwd=ROOT, check=True)
    with tarfile.open(archive) as tar:
        for member in tar.getmembers():
            destination = (root / member.name).resolve()
            assert destination.is_relative_to(root.resolve()) and not member.issym() and not member.islnk()
        tar.extractall(root)
    subprocess.run([sys.executable, '-c',
        'from pathlib import Path; from qgroup_core.storage import initialize; '
        'initialize(Path("empty.sqlite3")); initialize(Path("empty.sqlite3"))'], cwd=root, check=True)
    with sqlite3.connect(root / 'empty.sqlite3') as db:
        assert db.execute('PRAGMA integrity_check').fetchone()[0] == 'ok'
        assert not db.execute('PRAGMA foreign_key_check').fetchall()
        objects = db.execute("SELECT sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 ELSE 2 END,name").fetchall()
        assert db.execute("SELECT count(*) FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'").fetchone()[0] == 59
        sql = '\n'.join(row[0] + ';' for row in objects)
        # Migration ledger is historical schema provenance, not execution timestamps.
        versions = [row[0] for row in db.execute('SELECT version FROM schema_migrations ORDER BY version')]
        sql += '\n' + '\n'.join(f"INSERT INTO schema_migrations VALUES({v},'frozen-schema:{BASE}');" for v in versions)
    target = ROOT / 'packages/database/src/legacy-schema.ts'
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text('// Generated by tools/migration/export-legacy-schema.py from ' + BASE + '\n'
                      '// Empty synthetic database only; no member data. Do not edit.\n'
                      + 'export const legacySchema = ' + json.dumps(sql, ensure_ascii=False) + ';\n')
    print(f'Exported 59 user tables; migrations {versions}; {target.relative_to(ROOT)}')
